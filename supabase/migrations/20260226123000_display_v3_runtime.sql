CREATE TABLE IF NOT EXISTS public.display_call_events (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  sequence bigint GENERATED BY DEFAULT AS IDENTITY,
  patient_id uuid NOT NULL REFERENCES public.patients(id) ON DELETE CASCADE,
  destination text NOT NULL,
  called_by uuid NOT NULL REFERENCES auth.users(id),
  call_count integer NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT display_call_events_sequence_key UNIQUE (sequence)
);

CREATE TABLE IF NOT EXISTS public.display_sessions (
  id uuid PRIMARY KEY,
  user_id uuid NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
  device_name text NOT NULL DEFAULT 'display',
  heartbeat_at timestamptz NOT NULL DEFAULT now(),
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.display_call_acks (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  event_id uuid NOT NULL REFERENCES public.display_call_events(id) ON DELETE CASCADE,
  session_id uuid NOT NULL REFERENCES public.display_sessions(id) ON DELETE CASCADE,
  status text NOT NULL CHECK (status IN ('playing', 'played', 'failed')),
  error_message text,
  acknowledged_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT display_call_acks_unique_status UNIQUE (event_id, session_id, status)
);

CREATE INDEX IF NOT EXISTS idx_display_call_events_sequence ON public.display_call_events(sequence);
CREATE INDEX IF NOT EXISTS idx_display_call_events_created_at ON public.display_call_events(created_at DESC);
CREATE INDEX IF NOT EXISTS idx_display_sessions_heartbeat ON public.display_sessions(heartbeat_at DESC);
CREATE INDEX IF NOT EXISTS idx_display_call_acks_session_event ON public.display_call_acks(session_id, event_id);
CREATE INDEX IF NOT EXISTS idx_display_call_acks_status ON public.display_call_acks(status, acknowledged_at DESC);

ALTER TABLE public.display_call_events ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.display_sessions ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.display_call_acks ENABLE ROW LEVEL SECURITY;

DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_policies
    WHERE schemaname = 'public'
      AND tablename = 'display_call_events'
      AND policyname = 'Display call events are readable by authenticated users'
  ) THEN
    CREATE POLICY "Display call events are readable by authenticated users"
      ON public.display_call_events
      FOR SELECT
      TO authenticated
      USING (true);
  END IF;

  IF NOT EXISTS (
    SELECT 1 FROM pg_policies
    WHERE schemaname = 'public'
      AND tablename = 'display_sessions'
      AND policyname = 'Display sessions are accessible by owner'
  ) THEN
    CREATE POLICY "Display sessions are accessible by owner"
      ON public.display_sessions
      FOR ALL
      TO authenticated
      USING (user_id = auth.uid())
      WITH CHECK (user_id = auth.uid());
  END IF;

  IF NOT EXISTS (
    SELECT 1 FROM pg_policies
    WHERE schemaname = 'public'
      AND tablename = 'display_call_acks'
      AND policyname = 'Display call acks are readable by authenticated users'
  ) THEN
    CREATE POLICY "Display call acks are readable by authenticated users"
      ON public.display_call_acks
      FOR SELECT
      TO authenticated
      USING (true);
  END IF;
END
$$;

